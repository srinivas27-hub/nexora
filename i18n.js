  get(key) {
    const lang = this.currentLang;
    if (this.translations[lang] && this.translations[lang][key]) {
      return this.translations[lang][key];
    }
    if (this.translations.en && this.translations.en[key]) {
      return this.translations.en[key];
    }
    return key;
  },

  setLanguage(lang) {
    if (!['en', 'te', 'hi'].includes(lang)) return;
    this.currentLang = lang;
    localStorage.setItem('civic_lang', lang);
    document.documentElement.lang = lang;
    this.updateDom();
  },

  updateDom() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.get(key);
      if (text) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = text;
        } else {
          el.textContent = text;
        }
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const text = this.get(key);
      if (text) el.placeholder = text;
    });

    document.querySelectorAll('.lang-btn-option').forEach(btn => {
      const l = btn.getAttribute('data-lang');
      if (l === this.currentLang) {
        btn.classList.add('active');
      } else {
        btn.classList.remove('active');
      }
    });

    const langDisplay = document.getElementById('currentLangLabel');
    if (langDisplay) {
      if (this.currentLang === 'te') langDisplay.textContent = 'తెలుగు';
      else if (this.currentLang === 'hi') langDisplay.textContent = 'हिंदी';
      else langDisplay.textContent = 'English';
    }
  }
